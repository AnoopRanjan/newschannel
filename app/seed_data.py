def seed_database(db: Session):
    # Seed Categories
    for cat in CATEGORIES_DATA:
        existing = db.query(NewsCategory).filter(NewsCategory.slug == cat["slug"]).first()
        if not existing:
            db.add(NewsCategory(**cat))

    # Seed Ad Settings
    for ad in AD_SETTINGS_DATA:
        existing = db.query(AdSetting).filter(AdSetting.slot_name == ad["slot_name"]).first()
        if not existing:
            db.add(AdSetting(**ad))

    # Seed Channels
    now = datetime.utcnow()
    for ch in CHANNELS_DATA:
        existing = db.query(NewsChannel).filter(NewsChannel.slug == ch["slug"]).first()
        if not existing:
            channel_obj = NewsChannel(**ch)
            channel_obj.last_verified_at = now
            channel_obj.verification_status = "healthy"
            db.add(channel_obj)

    db.commit()
    print("Database seeding completed successfully.")
